// Helper maps
const ORDER_TO_LINK_MAP = new Map<number, JiaziHexagramLink>();
const NAME_TO_LINK_MAP = new Map<string, JiaziHexagramLink>();

JIAZI_HEXAGRAM_LINKS.forEach((link) => {
  ORDER_TO_LINK_MAP.set(link.order, link);
  NAME_TO_LINK_MAP.set(link.jiaziName.toLowerCase(), link);
});

export function getJiaziHexagramLink(orderOrName: number | string): JiaziHexagramLink | undefined {
  if (typeof orderOrName === "number") {
    return ORDER_TO_LINK_MAP.get(orderOrName);
  }
  const clean = orderOrName.toLowerCase().replace(/_/g, " ").trim();
  if (NAME_TO_LINK_MAP.has(clean)) {
    return NAME_TO_LINK_MAP.get(clean);
  }
  // Try finding by id or partial name
  return JIAZI_HEXAGRAM_LINKS.find(
    (item) => item.jiaziName.toLowerCase().includes(clean) || clean.includes(item.jiaziName.toLowerCase())
  );
}
