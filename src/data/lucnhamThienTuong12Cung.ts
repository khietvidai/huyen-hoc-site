/**
 * Tra cứu thông tin Tượng Thần khi Thiên Tướng ngự tại Địa Bàn Chi
 */
export function getThienTuongCungViInfo(
  tuongNameOrIndex: string | number,
  groundBranch: string
): {
  general: LucNhamThienTuongDetail;
  cungInfo?: LucNhamThienTuongCungVi;
} | undefined {
  const general = LUC_NHAM_THIEN_TUONG_12_CUNG_DATA.find((g) =>
    typeof tuongNameOrIndex === "number"
      ? g.id === tuongNameOrIndex + 1 || g.id === tuongNameOrIndex
      : g.name === tuongNameOrIndex || g.chinese === tuongNameOrIndex
  );

  if (!general) return undefined;
  const cungInfo = general.cungVi[groundBranch];
  return { general, cungInfo };
}


