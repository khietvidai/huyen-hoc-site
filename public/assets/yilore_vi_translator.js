  function translateNode(node) {
    if (!node) return;
    if (node.nodeType === Node.TEXT_NODE) {
      const orig = node.nodeValue;
      if (orig && /[\u4e00-\u9fa5\u3040-\u309f\u30a0-\u30ff]/.test(orig)) {
        const trans = translateText(orig);
        if (trans !== orig) {
          node.nodeValue = trans;
        }
      }
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      const tag = node.tagName.toLowerCase();
      if (tag === 'script' || tag === 'style' || tag === 'noscript') return;

      // Input attributes
      if (node.hasAttribute('placeholder')) {
        const ph = node.getAttribute('placeholder');
        if (ph && /[\u4e00-\u9fa5\u3040-\u309f\u30a0-\u30ff]/.test(ph)) node.setAttribute('placeholder', translateText(ph));
      }
      if (node.hasAttribute('title')) {
        const t = node.getAttribute('title');
        if (t && /[\u4e00-\u9fa5\u3040-\u309f\u30a0-\u30ff]/.test(t)) node.setAttribute('title', translateText(t));
      }
      if (node.hasAttribute('aria-label')) {
        const a = node.getAttribute('aria-label');
        if (a && /[\u4e00-\u9fa5\u3040-\u309f\u30a0-\u30ff]/.test(a)) node.setAttribute('aria-label', translateText(a));
      }

      for (let child = node.firstChild; child; child = child.nextSibling) {
        translateNode(child);
      }
    }
  }

